# Imports

from prompt_toolkit.key_binding import KeyBindings
from prompt_toolkit.filters import completion_is_selected
from prompt_toolkit import PromptSession
from prompt_toolkit.completion import Completer, Completion

import math
import ollama

# - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
# Settings

N_PREDICTIONS = 8
MODEL = "qwen2.5:3b"

# - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -

# Function used to compute, through an LLM, the next token candidates given a text.
def next_token_candidates(text, n = N_PREDICTIONS, model = MODEL):
    # Function to generate a reply from ollama give based on input text
    resp = ollama.generate(
        model = model,      # LLM to use
        prompt = text,      # Input text. In this case the previous text written
        raw = True,         # VERY IMPORTANT. From what I understand without raw = True the model receives also the system prompt. In this way receives only the text we submit and try to complete it
        options = {         # Options for input generation
            "num_predict": 1,   # Number of tokens predicted
            "temperature": 0.2, # How "random" is each token
        },
        top_logprobs = n,   # For each token predicted I can get n possible choiches
        logprobs = True,    # If True I get also the logprobs of each token predicted
    )
    
    # When I generate a response with logprobs = True I get a dictionary with the following key :
    # - "response" : the entire text generated by the model in a single string
    # - "logprobs" : a list of dictionaries, one for each token predicted. E.g. if num_predict = 1 I get a list with a single dictionary. If num_predict = 10 I get a list with 10 dictionaries. Each dictionary contains varioous information about the token(s) predicted for that position.
    # - OTHER : there are other keys that are not relevant for this task (e.g. "model", "total_duration", ...)
    choices = resp["logprobs"][0]["top_logprobs"]

    # For each token predicted I get a dictionary with the token in string format and the probability of that token
    return [(c["token"], math.exp(c["logprob"])) for c in choices]

# Function used to read the text written by the user and to generate the next token candidates based on that text. The function is called every time the user writes a character.
# This is not really important for the task since it is just a wrapper around the next_token_candidates function.
class DynamicCompleter(Completer):
    def get_completions(self, document, complete_event):
        text_before = document.text_before_cursor
        if not text_before :
            return

        # ALWAYS pass full context, not just the current word
        for tok, prob in next_token_candidates(text_before) :
            if text_before[-1].isspace():
                # After a space: token is a fresh next word — insert, replace nothing
                yield Completion(tok, start_position = 0, display = tok, display_meta = f"{prob:.2f}")
            else:
                # Mid-word: the model's tokens continue the current word;
                yield Completion(tok, start_position = 0, display = tok, display_meta = f"{prob:.2f}")

# - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
# Other cli related stuff. Basically creates an input field where the user can write text and attached to it the function that generates suggestions based on the text written by the user.

kb = KeyBindings()

# When a completion is highlighted, Enter accepts it and stays in the line
@kb.add('enter', filter = completion_is_selected)
def _(event) :
    event.current_buffer.complete_state = None   # accept + close menu, don't submit

session = PromptSession()
text = session.prompt('> ', completer = DynamicCompleter(), complete_while_typing = True, key_bindings = kb)
print(text)
